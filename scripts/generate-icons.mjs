const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = path.join(root, 'node_modules/@material-symbols/svg-400');
const outDir = path.join(root, 'src/components/icons');

// App icon name (spec RF-16) → name in the installed package, when they differ.
