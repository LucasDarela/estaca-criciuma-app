function readPaths(file) {
  if (!fs.existsSync(file)) {
    console.error(`Missing icon source: ${file}`);
    process.exit(1);
  }
  const svg = fs.readFileSync(file, 'utf8');
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) {
    console.error(`No <path> in ${file}`);
    process.exit(1);
  }
  return paths;
}

const entries = names.map((name) => {
  const source = aliases[name] ?? name;
  const outlined = readPaths(path.join(pkg, 'rounded', `${source}.svg`));
  const filled = readPaths(path.join(pkg, 'rounded', `${source}-fill.svg`));
  return `  ${name}: { outlined: ${JSON.stringify(outlined)}, filled: ${JSON.stringify(filled)} },`;
});

const output = `// Generated by scripts/generate-icons.mjs. Do not edit.
export const glyphs = {
${entries.join('\n')}
} as const satisfies Record<string, { outlined: readonly string[]; filled: readonly string[] }>;

export type IconName = keyof typeof glyphs;

export const iconViewBox = '0 -960 960 960';
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'glyphs.ts'), output);
fs.copyFileSync(path.join(pkg, 'LICENSE'), path.join(outDir, 'LICENSE'));
console.log(`Wrote ${names.length} icons.`);
